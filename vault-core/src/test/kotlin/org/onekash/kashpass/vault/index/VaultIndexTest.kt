    @Test
    fun `search matches tags an entry inherits from its groups`() {
        val tagged = VaultIndex.from(fixture("keepass2-kdbx41-tags.kdbx"))
        assertEquals(listOf("Example Bank"), tagged.rows(Chip.All, "money").map { it.title })
        val bank = tagged.rows(Chip.All, "money").single()
        val match = assertNotNull(tagged.matchFor(bank.id, "money"))
        assertEquals(MatchSource.TAG, match.source)
        assertEquals(listOf("finance", "important"), tagged.details(bank.id)!!.tags)
    }

    @Test
    fun `the reason is the first field holding any included word, highlighting the word that starts first`() {
        val index = VaultIndex.from(vault(root(entries = listOf(entry("Example Bank", user = "alice", notes = "login for alice")))))
        val row = index.rows(Chip.All, "alice bank").single()
        val match = assertNotNull(index.matchFor(row.id, "alice bank"))
        assertEquals(MatchSource.TITLE, match.source)
        assertEquals("Bank", "Example Bank".substring(match.textRange))
        val byNotes = assertNotNull(index.matchFor(row.id, "for -bob"))
        assertEquals(MatchSource.NOTES, byNotes.source)
        assertNull(index.matchFor(row.id, "-bob"))
        assertNull(index.matchFor(row.id, "bank -alice"))
    }

    private companion object {
        fun fixture(name: String): VaultDocument = documentOf(KdbxHeaderParserTest.fixture(name))

        fun entry(title: String, user: String = "", notes: String = "") = Entry(
            uuid = UUID.randomUUID(),
            fields = listOf(
                "Title" to Value.Plain(title),
                "UserName" to Value.Plain(user),
                "Password" to Value.Protected("secret"),
                "Notes" to Value.Plain(notes),
            ),
        )

        fun group(name: String, entries: List<Entry> = listOf(), groups: List<Group> = listOf()) =
            Group(name = name, entries = entries, groups = groups)

        fun root(entries: List<Entry> = listOf(), groups: List<Group> = listOf()) =
            group("Root", entries, groups)

        fun vault(root: Group, recycleBin: UUID? = null) = Doc(root, recycleBin)
    }
