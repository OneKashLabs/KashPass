    @Test
    fun `filtering 1000 entries takes under 100 ms`() {
        val entries = (1..1000).map { entry("Service $it", user = "user$it", notes = "note text $it") }
        val index = VaultIndex.from(vault(root(entries = entries)))
        repeat(20) { index.rows(Chip.All, "ser") }
        val times = (1..9).map { measureNanoTime { index.rows(Chip.All, "note text 99") } }.sorted()
        val medianMs = times[times.size / 2] / 1_000_000.0
        assertTrue(medianMs < 100.0, "median $medianMs ms")
        // Words match separately: "99" also occurs in titles and user names 99, 199, ... 999,
        // 990-998.
        assertEquals(19, index.rows(Chip.All, "note text 99").size)
        assertEquals(11, index.rows(Chip.All, "\"note text 99\"").size)
    }

    @Test
    fun `tags split on comma and semicolon only, as KeePass 2 does`() {
        val xml = TestVaults.keePassXml(
            entries = "<Entry><UUID>AAAAAAAAAAAAAAAAAAAAAg==</UUID><String><Key>Title</Key><Value>T</Value></String>" +
                "<Tags>work:mail, home;  ;travel</Tags></Entry>",
        )
        val index = VaultIndex.from(documentOf(TestVaults.rawXmlVault(xml)))
        assertEquals(1, index.rows(Chip.All, "work:mail").size)
        assertEquals(SearchMatch(MatchSource.TAG, null, 0..8, "work:mail", 0..8), index.matchFor(index.rows(Chip.All, "").single().id, "work:mail"))
        for (tag in listOf("home", "travel")) assertEquals(1, index.rows(Chip.All, tag).size, tag)
    }

