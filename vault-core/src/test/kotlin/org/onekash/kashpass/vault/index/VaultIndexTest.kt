    @Test
    fun `every word must match some field, in any order, as KeePass 2's simple search`() {
        val index = VaultIndex.from(vault(root(entries = listOf(
            entry("Example Bank", user = "alice", notes = "online login page"),
            entry("Example Mail", user = "bob", notes = "webmail login"),
        ))))
        assertEquals(listOf("Example Bank"), index.rows(Chip.All, "bank login").map { it.title })
        assertEquals(listOf("Example Bank"), index.rows(Chip.All, "LOGIN   alice").map { it.title })
        assertEquals(emptyList(), index.rows(Chip.All, "bank bob"))
        assertEquals(listOf("Example Mail"), index.rows(Chip.All, "login -alice").map { it.title })
        assertEquals(listOf("Example Bank"), index.rows(Chip.All, "\"online login\"").map { it.title })
        assertEquals(emptyList(), index.rows(Chip.All, "\"bank login\""))
    }

    @Test
    fun `a query of only quotes matches every entry outside the recycle bin, a blank one keeps the chip`() {
        val bin = group("Recycle Bin", entries = listOf(entry("Old")))
        val work = group("Work", entries = listOf(entry("Desk")))
        val index = VaultIndex.from(vault(root(entries = listOf(entry("Live")), groups = listOf(work, bin)), recycleBin = bin.uuid))
        val chip = index.chips.filterIsInstance<Chip.Group>().single()
        assertEquals(listOf("Desk", "Live"), index.rows(chip, "\"\"").map { it.title })
        assertEquals(listOf("Desk"), index.rows(chip, "   ").map { it.title })
        assertNull(index.matchFor(index.rows(chip, "\"\"").first().id, "\"\""))
    }

    @Test
    fun `search ignores accents both ways`() {
