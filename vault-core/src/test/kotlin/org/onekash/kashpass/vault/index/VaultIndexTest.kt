    // A file can repeat entry and group ids; KashPass must not crash or mix them up.
    @Test
    fun `repeated entry and group ids get distinct row ids, chips and details`() {
        val sharedEntry = UUID.randomUUID()
        val sharedGroup = UUID.randomUUID()
        val first = entry("First").copy(uuid = sharedEntry)
        val second = entry("Second").copy(uuid = sharedEntry)
        val a = Group(name = "Alpha", entries = listOf(first), uuid = sharedGroup)
        val b = Group(name = "Beta", entries = listOf(second), uuid = sharedGroup)
        val index = VaultIndex.from(vault(root(groups = listOf(a, b))))

        val rows = index.rows(Chip.All, "")
        assertEquals(listOf("First", "Second"), rows.map { it.title })
        assertEquals(2, rows.map { it.id }.toSet().size)
        assertEquals(listOf("First", "Second"), rows.map { index.details(it.id)?.title })

        val chips = index.chips.filterIsInstance<Chip.Group>()
        assertEquals(listOf("Alpha", "Beta"), chips.map { it.label })
        assertEquals(2, chips.map { it.id }.toSet().size)
        assertEquals(listOf(listOf("First"), listOf("Second")), chips.map { chip -> index.rows(chip, "").map { it.title } })
    }

    // Standard fields are protected by password only whatever the file's MemoryProtection says,
    // so these fields are shown and searched.
    @Test
    fun `standard fields stored protected are shown and searched`() {
        fun secret(text: String) = Value.Protected(text)
        val stored = Entry(
            uuid = UUID.randomUUID(),
            fields = listOf(
                "Title" to secret("stored-title"),
                "UserName" to secret("stored-user"),
                "URL" to secret("https://stored.example"),
                "Notes" to secret("stored notes"),
            ),
        )
        val index = VaultIndex.from(vault(root(entries = listOf(stored, entry("Visible")))))
        for (query in listOf("stored-title", "stored-user", "stored.example", "stored notes")) {
            assertEquals(listOf("stored-title"), index.rows(Chip.All, query).map { it.title }, query)
        }
        val details = index.details(index.rows(Chip.All, "stored-user").single().id)!!
        assertEquals(listOf(false, false, false), details.fields.map { it.isProtected })
    }

    @Test
    fun `masking and search follow the fixed protection, password only, not the file's Meta`() {
        val index = VaultIndex.from(documentOf(TestVaults.metaProtectedVault()))
        assertEquals(listOf("Meta Protected"), index.rows(Chip.All, "eve meta.example \"meta notes\"").map { it.title })
        assertEquals(emptyList(), index.rows(Chip.All, "plain-pass"))
        assertEquals(emptyList(), index.rows(Chip.All, "4711"))
        assertEquals(listOf("Meta Protected"), index.rows(Chip.All, "third").map { it.title })
        val details = index.details(index.rows(Chip.All, "eve").single().id)!!
        assertEquals(
            listOf("UserName" to false, "Password" to true, "URL" to false, "PIN" to true, "Floor" to false, "Notes" to false),
            details.fields.map { it.name to it.isProtected },
        )
        assertEquals("plain-pass", details.fields.single { it.name == "Password" }.value.reveal())
        assertEquals("meta notes", details.fields.single { it.name == "Notes" }.value.reveal())
    }

    @Test
    fun `recycled entries stay out of All and search, and show under the recycle bin chip`() {
        val bin = group("Recycle Bin", entries = listOf(entry("Old Bank Login")))
        val db = vault(root(entries = listOf(entry("Live")), groups = listOf(bin)), recycleBin = bin.uuid)
        val index = VaultIndex.from(db)

