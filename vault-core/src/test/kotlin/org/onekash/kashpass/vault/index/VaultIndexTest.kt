    @Test
    fun `every row id names the same entry the edits find`() {
        for (bytes in listOf(TestVaults.browserVault(aesRounds = 1_000UL), TestVaults.repeatedIdsVault(), KdbxHeaderParserTest.fixture("keepass2-desktop-new-database.kdbx"))) {
            val document = documentOf(bytes)
            val index = VaultIndex.from(document)
            val byEdits = org.onekash.kashpass.vault.doc.DocumentIds.entries(document)
            val rows = index.rows(Chip.All, "") + index.rows(Chip.RecycleBin, "")
            assertEquals(byEdits.keys, rows.map { it.id }.toSet())
            for (row in rows) {
                val title = byEdits.getValue(row.id).children("String").firstOrNull { it.child("Key")?.text() == "Title" }?.child("Value")?.text()?.takeIf { it.isNotEmpty() }
                assertEquals(row.title, title, row.id)
            }
        }
    }

    @Test
    fun `details and rows carry the entry's times, expiry only when it expires, and its tags`() {
        val created = Instant.parse("2024-03-12T09:30:00Z")
        val modified = Instant.parse("2026-10-18T14:00:00Z")
        val expiry = Instant.parse("2026-10-01T00:00:00Z")
        val expiring = entry("Expiring").copy(
            times = Times(created, null, modified, null, expiry, expires = true),
            tags = listOf("work", "bank"),
        )
        val notExpiring = entry("Not expiring").copy(times = Times(created, null, modified, null, expiry, expires = false))
        val noTimes = entry("No times").copy(times = null)
        val index = VaultIndex.from(vault(root(listOf(expiring, notExpiring, noTimes))))
        val rows = index.rows(Chip.All, "").associateBy { it.title }

        val details = index.details(rows.getValue("Expiring").id)!!
        assertEquals(created, details.created)
        assertEquals(modified, details.modified)
        assertEquals(expiry, details.expiry)
        assertEquals(listOf("work", "bank"), details.tags)
        assertEquals(expiry, rows.getValue("Expiring").expiry)

        assertNull(index.details(rows.getValue("Not expiring").id)!!.expiry, "Expires False keeps no expiry")
        assertNull(rows.getValue("Not expiring").expiry)
        val bare = index.details(rows.getValue("No times").id)!!
        assertEquals(listOf<Instant?>(null, null, null), listOf(bare.created, bare.modified, bare.expiry))
        assertEquals(emptyList(), bare.tags)
    }

